export type StringKey = keyof typeof STRINGS;

// Arabic is the default. Only an explicit 'en' choice switches to English.
let lang: Lang = (localStorage.getItem('mf_lang') as Lang) === 'en' ? 'en' : 'ar';

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  lang = next;
  localStorage.setItem('mf_lang', next);
  document.documentElement.lang = next;
  document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
}

export function applyLang(): void {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

export function t(key: StringKey): string {
  return STRINGS[key][lang];
}

/** Interpolates {name} placeholders after translation. */
export function tx(key: StringKey, vars: Record<string, string | number> = {}): string {
  let s: string = STRINGS[key][lang];
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

