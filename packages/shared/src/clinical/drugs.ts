export const DRUGS_BY_ID: Record<string, Drug> = Object.fromEntries(DRUG_CATALOG.map((d) => [d.id, d]));

export function getDrug(id: string): Drug | undefined {
  return DRUGS_BY_ID[id];
}

export function requireDrug(id: string): Drug {
  const d = getDrug(id);
  if (!d) throw new Error(`Unknown drug: ${id}`);
  return d;
}

/** Loose lookup: matches by drug id, generic name or brand name (case-insensitive). */
export function findDrugsByName(query: string): Drug[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return DRUG_CATALOG.filter(
    (d) =>
      d.id === q ||
      d.genericName.toLowerCase().includes(q) ||
      d.genericName.toLowerCase().startsWith(q) ||
      d.brandNames.some((b) => b.toLowerCase().includes(q)),
  );
}

/**
 * Resolve a free-text medication string from a patient record into a catalog
 * drug. Handles brand names ("Zoloft" -> sertraline), dosage suffixes
 * ("Metformin 500mg") and "20/40" style combination names.
 */
export function resolveMedicationString(input: string): Drug | null {
  const cleaned = input
    .replace(/\b\d+\s*(mg|mcg|g|ml|iu|units?|%)\b/gi, '')
    .replace(/[,()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return null;
  const direct = findDrugsByName(cleaned);
  if (direct.length) return direct[0]!;
  // "amoxicillin clavulanate" style
  return findDrugsByName(cleaned.replace(/\s*\/\s*/g, ' '))[0] ?? null;
}

/** All drugs whose `conditions` intersect the given condition keywords. */
export function drugsForCondition(condition: string, specialties?: readonly Specialty[]): Drug[] {
  const c = condition.toLowerCase().trim();
  if (!c) return [];
  const tokens = tokenizeCondition(c);
  return DRUG_CATALOG.filter((d) => {
    if (specialties && specialties.length && !d.specialties.some((s) => specialties.includes(s))) return false;
    return d.conditions.some((cond) => {
      const ct = cond.toLowerCase();
      if (ct === c) return true;
      return tokens.some((t) => ct.includes(t));
    });
  }).sort((a, b) => b.conditions.length - a.conditions.length);
}

function tokenizeCondition(condition: string): string[] {
  const stop = new Set(['disease', 'disorder', 'syndrome', 'of', 'the', 'and', 'type', 'a', 'an', 'in']);
  return condition
    .split(/[^a-z0-9]+/)
    .map((t) => t.trim())
    .filter((t) => t.length > 2 && !stop.has(t));
}

export function drugsByClass(className: string): Drug[] {
  const c = className.toLowerCase();
  return DRUG_CATALOG.filter((d) => d.class.toLowerCase().includes(c) || (d.subClass?.toLowerCase().includes(c) ?? false));
}

export function drugsByIds(ids: readonly string[]): Drug[] {
  return ids.map((id) => DRUGS_BY_ID[id]).filter((d): d is Drug => Boolean(d));
}

/** Highest-priority monitoring lab for a drug, used by the follow-up engine. */
export function primaryMonitoringVital(drug: Drug): string | null {
  const text = drug.monitoring.join(' ').toLowerCase();
  if (text.includes('fasting') || text.includes('glucose') || text.includes('a1c')) return 'fasting_glucose';
  if (text.includes('potassium')) return 'serum_potassium';
  if (text.includes('creatinine') || text.includes('renal')) return 'creatinine';
  if (text.includes('inr')) return 'creatinine';
  if (text.includes('lipid') || text.includes('ldl')) return 'ldl';
  if (text.includes('blood pressure')) return 'systolic_bp';
  if (text.includes('haemoglobin') || text.includes('hemoglobin')) return 'hemoglobin';
  return null;
}
