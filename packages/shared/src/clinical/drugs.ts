/**
 * Structured drug catalog used by the decision-support engine and the
 * prescription builder.
 *
 * Doses are *adult maintenance starting doses for reference*. They are surfaced
 * as suggestions only — the UI always requires clinician confirmation, and
 * paediatric/pregnancy/renal/dosing overrides are computed separately in
 * `dosing.ts`.
 */

import type { Specialty } from '../domain/enums.js';

export type DrugRoute = 'oral' | 'iv' | 'im' | 'subcutaneous' | 'topical' | 'inhaled' | 'rectal' | 'ophthalmic' | 'intranasal';

export interface DrugStrength {
  label: string;
  /** mg per unit, or percent for topical. */
  amount: number;
  unit: string;
}

export interface Drug {
  id: string;
  genericName: string;
  brandNames: string[];
  /** ATC-ish therapeutic class, used for allergy cross-reactivity. */
  class: string;
  /** Sub-class, e.g. "biguanide". */
  subClass: string | null;
  form: string | null;
  strengths: DrugStrength[];
  route: DrugRoute;
  typicalDose: string;
  frequency: string;
  maxDose: string | null;
  durationDays: number | null;
  indication: string;
  /** Conditions this drug is used for — powers diagnosis-based lookup. */
  conditions: string[];
  specialties: Specialty[];
  renalCaution: string | null;
  hepaticCaution: string | null;
  monitoring: string[];
  contraindications: string[];
  /** Pregnancy categories: 'a' | 'b' | 'c' | 'd' | 'x'. */
  pregnancy: 'a' | 'b' | 'c' | 'd' | 'x';
  lactation: 'compatible' | 'caution' | 'avoid';
  pediatricApproved: boolean;
  ageMinYears: number;
  /** Maximum single dose for OTC-style counselling. */
  otcMaxDailyDose: string | null;
  /** Notes surfaced as counselling points. */
  counselling: string[];
  /** Whether the clinic likely stocks this item. */
  dispensable: boolean;
  /** Cost hint for the pharmacy module, in minor units. */
  unitCostMinor: number | null;
}

function drug(d: Drug): Drug {
  return d;
}

